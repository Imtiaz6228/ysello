import type { CatalogProduct } from "./catalog";

type DemoProductInput = {
  slug: string;
  category: string;
  categorySlug: string;
  title: string;
  description: string;
  priceCents: number;
  originalPriceCents?: number;
  imageUrl: string;
  platform: string;
  region?: string;
  seller?: string;
  badge?: string;
  type?: "DOWNLOAD" | "SERVICE";
  delivery?: string;
  rating?: number;
  reviews?: number;
  sales?: string;
  stockCount?: number;
};

function demoProduct(
  input: DemoProductInput,
  index: number,
): CatalogProduct {
  const seller = input.seller ?? "Ysello Select";
  const type = input.type ?? "DOWNLOAD";
  return {
    id: `ysello-demo-${String(index + 1).padStart(3, "0")}`,
    slug: input.slug,
    category: input.category,
    categorySlug: input.categorySlug,
    title: input.title,
    description: input.description,
    longDescription: `${input.description} This marketplace listing clearly shows the supported platform, delivery format, region and seller terms before checkout. Delivery and support remain connected to the protected Ysello order record.`,
    seller,
    sellerSlug: seller.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
    priceCents: input.priceCents,
    originalPriceCents: input.originalPriceCents,
    rating: input.rating ?? 4.8,
    reviews: input.reviews ?? 184 + index * 11,
    sales: input.sales ?? `${1.2 + (index % 8) * 0.4}k`,
    delivery:
      input.delivery ??
      (type === "SERVICE" ? "1–3 business days" : "Instant digital delivery"),
    badge: input.badge ?? (index % 4 === 0 ? "Bestseller" : "Popular"),
    type,
    icon: input.title.slice(0, 2).toUpperCase(),
    imageUrl: input.imageUrl,
    stockCount: input.stockCount ?? (type === "SERVICE" ? 20 : 250 + index * 7),
    included:
      type === "SERVICE"
        ? ["Defined service scope", "Written delivery summary", "Revision window"]
        : ["Digital product", "Activation or delivery guide", "Order-linked support"],
    license:
      type === "SERVICE"
        ? "Seller-delivered professional service"
        : "Single-user marketplace license",
    formats: type === "SERVICE" ? ["Protected order delivery"] : ["Digital code"],
    version: "Current",
    updatedAt: "July 2026",
    publishedAt: new Date(2026, 6, Math.max(1, 28 - index)).toISOString(),
    facts: {
      platform: input.platform,
      region: input.region ?? "GLOBAL",
      productKind: type === "SERVICE" ? "Professional service" : "Digital key",
      deliveryMethod:
        type === "SERVICE" ? "Seller delivery" : "Instant delivery",
    },
    warranty: "Delivery support is available through the order workspace.",
    refundPolicy:
      "Eligibility is reviewed under the marketplace digital-product policy.",
  };
}

